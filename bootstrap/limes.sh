#!/usr/bin/env bash
set -euo pipefail

# Installs `lim` (the limes host-mirroring sandbox). limes has its own repo; dotfiles
# carries it as the `vendor/limes` submodule, the same way it carries the zsh plugins,
# so a fresh machine needs no manual clone. `make bootstrap-limes` chains the rest
# (prereqs, config drop-in, `lim bootstrap`).

DOTFILES_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# LIMES_REPO wins, so a machine where limes is being *developed* builds that working tree
# instead of the pinned submodule.
REPO="${LIMES_REPO:-$DOTFILES_DIR/vendor/limes}"
stamp_file="${XDG_DATA_HOME:-$HOME/.local/share}/limes/.installed-commit"

# What a build here would produce. `lim --version` cannot answer this -- it has read 0.1.0
# since the first commit -- so without a stamp any installed `lim` looks current and a
# submodule bump can never reach the machine that needs it.
#
# The superproject's index entry is the fallback because it is readable even when the
# submodule has never been checked out, which is exactly when we must not claim to be
# up to date.
limes_commit() {
    if [[ -e "$REPO/.git" ]]; then
        local commit
        commit="$(git -C "$REPO" rev-parse HEAD 2>/dev/null)" || return 1
        if [[ -n "$(git -C "$REPO" status --porcelain 2>/dev/null)" ]]; then
            commit="$commit-dirty"
        fi
        printf '%s\n' "$commit"
    else
        git -C "$DOTFILES_DIR" rev-parse ":vendor/limes" 2>/dev/null || return 1
    fi
}

# Machine-local limes drop-in: the dotfiles repo, and the zsh history file.
#
# The repo goes in read-only.
#
# Docker flattens a symlink it mounts, but not the symlinks *inside* a mounted directory:
# ~/.config goes in ro, and every tracked config under it -- fastfetch, and whatever the
# repo backs next -- is a symlink into this repo, so they all dangle in the sandbox unless
# the repo is there too. The drop-in dotfiles.toml solves this for the zsh files alone,
# with `link = "parent"`, and only reaches the one directory each of them lives in.
#
# Generated rather than symlinked like dotfiles.toml because the repo sits at a different
# absolute path on each machine, which is exactly what a synced file cannot say.
#
# The history file goes in read-write, so suggestions inside are the host's and commands
# run inside are there next time on either side. It is generated here rather than declared
# in the synced dotfiles.toml because this script can also *create* the file: limes hard-
# fails on a config mount whose path is missing, so a machine that has never run zsh would
# otherwise break every `lim run`. `optional` covers deleting it later.
write_repo_dropin() {
    local dropin="${XDG_CONFIG_HOME:-$HOME/.config}/limes/config.d/dotfiles-repo.toml"
    local histfile="$HOME/.histfile"
    if [[ ! -e "$histfile" ]]; then
        : > "$histfile"
        chmod 600 "$histfile"
        echo "Created $histfile (empty; zsh's HISTFILE)"
    fi

    local content
    content="$(cat <<EOF
# Generated by dotfiles bootstrap/limes.sh. Machine-local -- do not sync.
#
# The repo behind every tracked dotfile. Without it the symlinks inside the mounted
# ~/.config point at nothing in the sandbox. Read-only: a sandboxed process has no business
# rewriting the shell startup files of the host it is running on.
[mounts]
"$DOTFILES_DIR" = "ro"

# Read-write and shared with the host on purpose: zsh-autosuggestions has nothing to
# suggest from an empty history, and INC_APPEND_HISTORY wants somewhere to append after
# every command. The cost is that a sandboxed process can read -- and rewrite -- every
# command you have ever run on this machine.
"~/.histfile" = { mode = "rw", optional = true }
EOF
)"
    # Compare before writing so a re-run is genuinely a no-op rather than a fresh mtime.
    if [[ "$(cat "$dropin" 2>/dev/null || true)" != "$content" ]]; then
        mkdir -p "$(dirname "$dropin")"
        printf '%s\n' "$content" > "$dropin"
        echo "Wrote $dropin"
    fi
}
write_repo_dropin

want="$(limes_commit || true)"
have="$(cat "$stamp_file" 2>/dev/null || true)"

# A dirty tree never matches: its commit says nothing about the uncommitted edit someone
# is presumably trying to test.
if command -v lim &>/dev/null && [[ -n "$want" && "$want" == "$have" && "$want" != *-dirty ]]
then
    echo "lim is already installed and current: $(lim --version) ($want)"
    exit 0
fi

# An uninitialised submodule is an empty directory, not a missing one.
if [[ ! -f "$REPO/Cargo.toml" ]]; then
    if [[ -z "${LIMES_REPO:-}" ]]; then
        echo "Fetching the limes submodule..."
        (cd "$DOTFILES_DIR" && git submodule update --init vendor/limes)
    fi
    if [[ ! -f "$REPO/Cargo.toml" ]]; then
        echo "No limes checkout at $REPO (no Cargo.toml)."
        echo "Run \`make submodules\`, or set LIMES_REPO=/path/to/limes."
        exit 1
    fi
    want="$(limes_commit || true)"
fi

# Same fallback the Makefile uses for `lim`: when bootstrap-rust just installed rustup in
# this very run, cargo exists but is not on PATH yet.
CARGO="$(command -v cargo || echo "$HOME/.cargo/bin/cargo")"
if [[ ! -x "$CARGO" ]]; then
    echo "cargo not found — run \`make bootstrap-rust\` first, then re-run."
    exit 1
fi

if command -v lim &>/dev/null; then
    echo "Rebuilding lim from $REPO (installed: ${have:-unknown}, wanted: ${want:-unknown})..."
else
    echo "Installing lim from $REPO..."
fi
"$CARGO" install --path "$REPO"

# Only after a build that succeeded: a stamp written eagerly would mark a failed install
# as current and skip the retry.
mkdir -p "$(dirname "$stamp_file")"
printf '%s\n' "$want" > "$stamp_file"
echo "lim installed ($want)."
